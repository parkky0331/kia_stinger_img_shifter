#!/usr/bin/env python3
"""Generates src/dev/stinger/imgshifter/TopCar.java, the only picture this mod ships.

The surround-view car is part of the camera unit's video, so the head unit has no stock picture of
it that could be repainted. For the overlay (Around) the mod brings its own top-down car: a silver
fastback I generated with an AI image tool from a text description only (no photo, no model name),
then cut out, evened out the paint and scaled to the size of the car on screen.

usage: python3 tools/topcar.py <car.webp> <paint.png> <tail.webp> <tail-paint.png> <nose.webp> <nose-paint.png>
  car.webp   the silver car from above, nose up, on a transparent background, at display size
  paint.png  mask of its painted areas (white), same size; glass and lamps are left out
  tail.webp, tail-paint.png
             the same car's rear end at the size of the large view (looking down behind the car)
  nose.webp, nose-paint.png
             its front at that size (looking down ahead of the car)
"""
import base64
import os
import sys

from PIL import Image

car, paint, tail, tail_paint, nose, nose_paint = sys.argv[1:7]
size, tail_size, nose_size = Image.open(car).size, Image.open(tail).size, Image.open(nose).size
if Image.open(paint).size != size or Image.open(tail_paint).size != tail_size or Image.open(nose_paint).size != nose_size:
    sys.exit('a picture and its paint mask are not the same size')


def text(path):
    data = base64.b64encode(open(path, 'rb').read()).decode('ascii')
    if len(data) > 60000:
        sys.exit(path + ' is too large for one constant')
    lines = [data[i:i + 120] for i in range(0, len(data), 120)]
    return '\n            + '.join('"%s"' % line for line in lines)


out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'dev', 'stinger', 'imgshifter', 'TopCar.java')
with open(out, 'w') as f:
    f.write('''package dev.stinger.imgshifter;

/**
 * The only picture this mod ships (generated by tools/topcar.py, don't edit by hand): a silver
 * top-down car for the surround-view overlay, %d x %d, with a mask of its painted areas, plus its
 * rear end (%d x %d) and front (%d x %d) at the size of the large views. Each is an image file in
 * Base64 (WebP and PNG).
 */
final class TopCar {
    private TopCar() {}

    static final int W = %d, H = %d;
    static final String CAR = %s;
    static final String PAINT = %s;
    static final int TAIL_W = %d, TAIL_H = %d;
    static final String TAIL = %s;
    static final String TAIL_PAINT = %s;
    static final int NOSE_W = %d, NOSE_H = %d;
    static final String NOSE = %s;
    static final String NOSE_PAINT = %s;
}
''' % (size[0], size[1], tail_size[0], tail_size[1], nose_size[0], nose_size[1], size[0], size[1], text(car), text(paint), tail_size[0], tail_size[1], text(tail),
       text(tail_paint), nose_size[0], nose_size[1], text(nose), text(nose_paint)))
print(out, os.path.getsize(out), 'bytes')
